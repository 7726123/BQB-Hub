// 对话模式的提示词块（与 lib/bubble.ts 的解析器成对：改格式块必须同步改解析器/测试）。
// 刻意不做成用户可编辑的预设模块——格式块被改坏，整个模式的渲染就废了。
// 注入位置：预设模块之后、世界书之前（稳定前缀区；只在设置变化时变，不影响 prompt 缓存命中）。

export const CHAT_BLOCK_VERSION = 5;

export interface ChatBlockOpts {
  roster: string[];        // 角色名单（世界书「角色」条目名 + 主角名）
  protagonist?: string;    // 主角名（可为空）
  lengthWords?: number | string;  // 预设「字数」模块要求的字数（只写数字，避免与模块正文重复注入）
}

// 角色名单：世界书「角色」条目名 + 主角名（去重、保持书内顺序）
export function chatRoster(entries: Array<{ type?: string; name?: string }> | null | undefined, protagonistName?: string): string[] {
  const out: string[] = [];
  const push = (n: string) => { const s = String(n || '').trim(); if (s && out.indexOf(s) < 0) out.push(s); };
  (entries || []).forEach(e => { if (e && e.type === '角色') push(e.name || ''); });
  push(protagonistName || '');
  return out;
}

// 注：文案里的 {{}} 是给调用方做替换的占位符，不是模板引擎。
export function chatFormatBlock(o: ChatBlockOpts): string {
  const roster = (o.roster || []).filter(Boolean);
  const prot = String(o.protagonist || '').trim();
  // 名单里给主角加标记：不加的话主角名和普通 NPC 一样躺在名单里，模型会把他当"名单里的另一个角色"
  // 演——实测症状是主角被拆成两个人物（姓/名各自的写法另起一个说话人，甚至并成「温水与和彦」）。
  const nameList = roster.length > 0
    ? roster.map(n => (prot && n === prot) ? n + '（作者本人·主角）' : n).join('、')
    : '（当前世界书还没有角色条目，用到谁就写谁的名字）';
  // 长度完全由预设决定：预设写了字数就按它（并在用户消息末尾重申一次，实测能明显提高命中率）；
  // 预设没写字数就**不注入任何数字**，只要求把场面演完、别一句就收（用户要求：字数不要由软件定）。
  const n = Number(o.lengthWords);
  const hasLen = Number.isFinite(n) && n > 0;
  const lenSection = hasLen
    ? `【长度（硬要求，优先于"把场面收住"）】
- 本次输出约 ${n} 字：写到字数再收尾，中途不要提前把场面收住。
- 同一个气泡里可以有不止一句话：连续几句台词、台词加动作，都放在一个气泡里（台词与描写各自成行）。
- 字数不够就继续往下演（下一句话、下一个动作），不要用总结、复述、大段心理独白注水。`
    : `【长度】
- 篇幅按预设要求；预设没有规定时，把这个场面自然演完：不要一句就收，也不用废话凑数。`;

  return `# 对话演出（本模式唯一的输出格式）

这个模式把故事演成一段聊天记录：读者看到的是一条条气泡，一条气泡 = 某个角色在某个瞬间说的话和做的事。

【格式】
1. 每个气泡另起一行，行首写「说话人：」。说话人从这份名单里取：${nameList}
   名单里的角色**必须用名单上的名字**，不要给他改名、起绰号或另造一个名字。名单之外只允许【临时龙套】那一节里说的写法。
   叙述、环境、没有明确说话人的独白，说话人写「白」，并且**单独一行**——不要跟在某个角色的台词后面（读者会以为那是这个角色做的）。
2. 台词一律用「」包住（**硬要求：全轮零例外**）。**说出口的话**——对白、喊话、回答、引述别人的原话、电话或广播里传出来的声音——全都用「」包住，
   包括只有一个字的回应（「嗯。」「哦。」「知道了。」）和重复别人的话；**漏一个引号，软件就会把它当动作显示成淡色**，读者就看不出谁在说话。
   反过来，**没说出口的一律不加引号**：动作、表情、心理与心声（心里想的、没出声的）、环境与旁白，全部直接写、不加任何符号。
   书名、歌名、标语、招牌或纸上的字、被强调的词语也**不要**用「」（书名用《》或直接写）——引号里的内容会被当成台词染色。
   一句话里台词与叙述混着写时，引号只包说出口的那半句，叙述留在引号外。
3. 属于某个角色的动作、表情、语气、心理，直接写、不加任何符号；并且**单独成行**——不要和台词挤在同一行（同一行里台词和描写连着写，读者分不清哪句是说出来的）。
4. 一个气泡里可以既有台词又有描写，顺序按实际发生的样子来：台词与描写各自成行，不要一行里"先台词后描写"串成一句。
5. 不写章节标题、不写序号、不用 markdown（\`**加粗**\`、#、- 列表都不写）、不写「（未完待续）」这类提示。
6. 不解释、不总结、不预告后文，不在结尾点评自己刚写的内容。
7. **输出前自检一遍**（这三条是软件分色的唯一依据，错了颜色的读者就看不懂谁在说话）：①「」里的每一句都是说出口的话；② 每一句说出口的话都在「」里（尤其是短回应、单字回应）；③ 没引号的句子都在写动作、心理、环境或旁白。

【这一轮怎么演】
- 一轮要演出**多个来回**：你来我往至少三轮，再停在有推进的地方；不要一问一答就收，字数没写够更不要提前收尾。
- 主角就是作者本人${prot ? '：名单里的 ' + prot + ' 和第一人称的「我」是同一个人' : '（本书没设主角名，作者的第一人称视角就是主角）'}。主角的戏由你照常演——可以说、可以做、可以有心理活动——作者只给方向，具体怎么写是你的活儿。
- 主角只有一个人，不许分身${prot ? '：不要用他的姓、名、简称、尊称、别名另开一个说话人，那些都指 ' + prot + ' 同一个人' : '：不要给主角另起名字，也不要把「我」当成名单里的某个角色'}；他本人不必像其他角色那样"出场"，但写他的行一定要归到他自己的气泡里。
- **作者的输入不会显示给读者**（读者只看到你演的这轮气泡），那是给你的方向/素材，你必须把它组织进演出里：
  · 作者写的是台词或动作（可能带「」或（））→ 写成对应角色的台词/动作：是谁说的就进谁的气泡，该配什么语气、表情、心理由你补，可以润色改写；不要出现「作者说……」这种身份，也不要把它原封不动抄成单独一行。
  · 作者写的是要求（如「让她说出理由」「推进到放学」「多说几句」）→ 照它演，但不要把要求本身写进演出。

【临时龙套：路人、店员、同学A 这类】
- 场面确实需要一个"名单外的外人"时（问路、围观、传话、点单、起哄、通报），允许它单独开气泡说话，
  名字用**通用称呼**：「路人甲」「同学A」「店员」「老板」「保安」「护士」「前台」这种三五个字的说法（不要带「的」），
  不要起有姓有名的正式人名（正式人物要进世界书才有设定和头像，临时造人名会让读者以为是重要角色）。
- 龙套要薄：一轮里最多 2 个龙套说话，每人一两句短台词，穿场面就走；**不写龙套的心理活动、不写背景设定、不给他独立的情节线**。
- 不要让龙套说出只有名单角色知道的事，也不要让龙套替名单角色做决定；他只是场面里的一个过路人。

【白尽量少，主角写厚】
- 白只用在画面、环境、群像这些归不到任何角色身上的地方；能落到某个角色身上的，不要给白。整轮白不超过 2～3 条。
- 第一人称的所见、所感、所想（"我把练习册合上""我盯着那道折痕"）都是主角本人的，写进主角自己的气泡里。
- 主角的气泡要写厚：一句台词可以带两三句心理或动作，不要只说一句就换人。
- 别人的心理只写从表情、动作、语气上看得出来的部分，不写全知判断。

${lenSection}`;
}

export default { chatFormatBlock, chatRoster, CHAT_BLOCK_VERSION };
